const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '..');
const crypto = require('node:crypto');
const wordcraftManifest = JSON.parse(fs.readFileSync(path.join(root, 'public/wordcraft/version.json'), 'utf8'));
if (!wordcraftManifest.chineseFont) throw new Error('Run scripts/prepare-cjk-font.py before building: the Web runtime needs Chinese fonts.');
for (const [name, expected] of Object.entries(wordcraftManifest.assets)) {
  const bytes = fs.readFileSync(path.join(root, 'public/wordcraft', name));
  if (bytes.length !== expected.bytes || crypto.createHash('sha256').update(bytes).digest('hex') !== expected.sha256) throw new Error(`Wordcraft asset checksum mismatch: ${name}`);
}
const editorModules = path.join(root, '_scratch/tmp/editor-deps/node_modules');
const uiModules = path.join(root, '_scratch/tmp/ui-deps/node_modules');
let esbuild;
try { esbuild = createRequire(path.join(uiModules, '../package.json'))('esbuild'); }
catch { esbuild = createRequire(path.join(editorModules, '../package.json'))('esbuild'); }
const common = { bundle: true, nodePaths: [uiModules, editorModules], loader: { '.css': 'text' }, jsx: 'transform', target: ['chrome130'], logLevel: 'warning' };
fs.mkdirSync(path.join(root, 'public'), { recursive: true });
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
esbuild.buildSync({ ...common, entryPoints: [path.join(root, 'src/shared/writing-document.mjs')], platform: 'node', format: 'esm', outfile: path.join(root, 'dist/writing-document.mjs') });
// Inline KaTeX fonts so the native panel and browser use the same rendering.
const katexDir = path.join(editorModules, 'katex/dist');
const katexCss = fs.readFileSync(path.join(katexDir, 'katex.min.css'), 'utf8').replace(/url\((fonts\/[^)]+)\)/g, (_, file) => `url(data:font/${file.endsWith('.woff2') ? 'woff2' : file.endsWith('.woff') ? 'woff' : 'ttf'};base64,${fs.readFileSync(path.join(katexDir, file)).toString('base64')})`);
fs.writeFileSync(path.join(root, 'src/client/katex.generated.css'), katexCss);
esbuild.buildSync({ ...common, entryPoints: [path.join(root, 'src/client/preview.jsx')], format: 'esm', outfile: path.join(root, 'public/preview.js') });
if (fs.existsSync(path.join(root, 'src/client/standalone.jsx'))) esbuild.buildSync({ ...common, entryPoints: [path.join(root, 'src/client/standalone.jsx')], format: 'esm', outfile: path.join(root, 'public/app.js') });
if (fs.existsSync(path.join(root, 'src/client/entry.jsx'))) {
  const result = esbuild.buildSync({ ...common, entryPoints: [path.join(root, 'src/client/entry.jsx')], format: 'cjs', external: ['react', 'react-dom'], write: false });
  fs.writeFileSync(path.join(root, 'client.js'), `/* Generated by scripts/build.cjs. Edit src/client instead. */\nwindow.__ModuleLoader__.load({id:'dsh-research-workbench',factory:(require)=>{var module={exports:{}};var exports=module.exports;\n${result.outputFiles[0].text}\nreturn module.exports;}});\n`);
}
console.log('Workbench client built.');
